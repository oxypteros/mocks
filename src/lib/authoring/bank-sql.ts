import type { ExamConfig } from './bank-source.ts';
import type { BankSettings, Question } from './schema.ts';

/**
 * Build the D1 seed SQL from the validated content source.
 *
 * The seed is scoped to one bank, it removes that bank's questions, modules,
 * and bank row, then inserts them again. The exam row is upserted because it is
 * shared by the exam and practice banks.
 */

function text(value: string | null | undefined): string {
	if (value === null || value === undefined) return 'NULL';
	return `'${value.replace(/'/g, "''")}'`;
}

function number(value: number | null | undefined): string {
	if (value === null || value === undefined) return 'NULL';
	return String(value);
}

function boolean(value: boolean): string {
	return value ? '1' : '0';
}

/** Authoring dates are ISO `YYYY-MM-DD` (D1 stores integer ms). */
function dateMs(value: string | null): string {
	if (!value) return 'NULL';
	const parsed = Date.parse(`${value}T00:00:00Z`);
	return Number.isFinite(parsed) ? String(parsed) : 'NULL';
}

function comment(value: string): string {
	return `-- ${value.replace(/\r?\n/g, ' ')}`;
}

export function buildBankSql(exam: ExamConfig, bank: BankSettings, questions: Question[]): string {
	const moduleOrder = new Map(bank.modules.map((module, index) => [module.id, index]));
	const ordered = [...questions].sort((left, right) => {
		const leftModule = moduleOrder.get(left.module) ?? Number.MAX_SAFE_INTEGER;
		const rightModule = moduleOrder.get(right.module) ?? Number.MAX_SAFE_INTEGER;
		return leftModule - rightModule || left.id.localeCompare(right.id);
	});

	const lines: string[] = [
		comment('Generated by `pnpm bank:build` from the content source. Do not edit.'),
		comment(`Bank: ${bank.id} v${bank.version}`),
		comment(`Exam: ${exam.id} (${exam.title})`),
		'',
		`DELETE FROM questions WHERE bank_id = ${text(bank.id)};`,
		`DELETE FROM modules WHERE bank_id = ${text(bank.id)};`,
		`DELETE FROM banks WHERE id = ${text(bank.id)};`,
		'',
		'INSERT INTO exams (',
		'\tid, slug, title, provider, provider_url, unofficial, content_locale,',
		'\tblueprint_version, duration_minutes, question_count, option_count,',
		'\tpass_percent, sampling, question_order, option_order, option_label_style,',
		'\tdisclaimer, status',
		') VALUES (',
		[
			text(exam.id),
			text(exam.slug),
			text(exam.title),
			text(exam.provider),
			text(exam.providerUrl),
			boolean(exam.unofficial),
			text(exam.contentLocale),
			text(exam.blueprintVersion),
			number(exam.durationMinutes),
			number(exam.questionCount),
			number(exam.optionCount),
			number(exam.passPercent),
			text(exam.sampling),
			text(exam.questionOrder),
			text(exam.optionOrder),
			text(exam.optionLabelStyle),
			text(exam.disclaimer),
			text(exam.status)
		]
			.map((value) => `\t${value}`)
			.join(',\n'),
		')',
		'ON CONFLICT(id) DO UPDATE SET',
		[
			'slug = excluded.slug',
			'title = excluded.title',
			'provider = excluded.provider',
			'provider_url = excluded.provider_url',
			'unofficial = excluded.unofficial',
			'content_locale = excluded.content_locale',
			'blueprint_version = excluded.blueprint_version',
			'duration_minutes = excluded.duration_minutes',
			'question_count = excluded.question_count',
			'option_count = excluded.option_count',
			'pass_percent = excluded.pass_percent',
			'sampling = excluded.sampling',
			'question_order = excluded.question_order',
			'option_order = excluded.option_order',
			'option_label_style = excluded.option_label_style',
			'disclaimer = excluded.disclaimer',
			'status = excluded.status',
			'updated_at = unixepoch() * 1000'
		]
			.map((value) => `\t${value}`)
			.join(',\n') + ';',
		'',
		`INSERT INTO banks (id, exam_id, kind, title, version, status) VALUES (`,
		[
			text(bank.id),
			text(exam.id),
			text(bank.kind),
			text(bank.title),
			text(bank.version),
			text(bank.status)
		]
			.map((value) => `\t${value}`)
			.join(',\n'),
		');',
		''
	];

	bank.modules.forEach((module, index) => {
		lines.push(
			'INSERT INTO modules (id, bank_id, title, position, question_count) VALUES (',
			[
				text(module.id),
				text(bank.id),
				text(module.title),
				number(index),
				number(module.questionCount)
			]
				.map((value) => `\t${value}`)
				.join(',\n'),
			');'
		);
	});
	lines.push('');

	for (const question of ordered) {
		if (question.images.length > 0) {
			throw new Error(`Question ${question.id} has images, which v0 does not seed.`);
		}
		if (question.type !== 'single') {
			throw new Error(`Question ${question.id} has unsupported type ${question.type}.`);
		}

		lines.push(
			'INSERT INTO questions (',
			'\tid, exam_id, bank_id, module_id, type, stem, explanation, difficulty,',
			'\ttags, status, provenance, reviewer, reviewed_at, source_checked_at',
			') VALUES (',
			[
				text(question.id),
				text(exam.id),
				text(bank.id),
				text(question.module),
				text(question.type),
				text(question.stem),
				text(question.explanation),
				number(question.difficulty),
				text(JSON.stringify(question.tags)),
				text(question.status),
				text(question.provenance),
				text(question.reviewer),
				dateMs(question.reviewedAt),
				dateMs(question.sourceCheckedAt)
			]
				.map((value) => `\t${value}`)
				.join(',\n'),
			');'
		);

		question.options.forEach((option, position) => {
			lines.push(
				'INSERT INTO options (id, question_id, position, text, short_label, rationale, is_correct) VALUES (',
				[
					text(option.id),
					text(question.id),
					number(position),
					text(option.text),
					text(option.shortLabel),
					text(option.rationale),
					boolean(option.id === question.correctOptionId)
				]
					.map((value) => `\t${value}`)
					.join(',\n'),
				');'
			);
		});

		question.references.forEach((reference, position) => {
			lines.push(
				'INSERT INTO question_references (question_id, position, kind, title, url, author, year, note) VALUES (',
				[
					text(question.id),
					number(position),
					text(reference.kind),
					text(reference.title),
					text(reference.url),
					text(reference.author),
					text(reference.year),
					text(reference.note)
				]
					.map((value) => `\t${value}`)
					.join(',\n'),
				');'
			);
		});

		lines.push('');
	}

	lines.push(comment('End of generated seed.'));
	return `${lines.join('\n')}\n`;
}
